// Builds the daemon's service files into dist/service/ (or the directory given):
// - daemon.mjs: daemon/cli.ts and everything it imports, bundled into one ES module;
// - vendor/playwright-core/: playwright-core as published, minus what the daemon never loads.
//   It cannot be bundled: it forks lib/entry/oopBrowserDownload.js to install browsers and reads
//   package.json, browsers.json and a wasm file next to itself. daemon.mjs imports it by relative
//   path, so the directory needs no node_modules (which npm leaves out of published packages).
// - capybara-install-key: the Chromium revisions it installs (daemon/install-key.ts), which a
//   capybara-device with the machine-wide install cache keys the browser install by.
// Every file under the output directory is one service file; the service entry is daemon.mjs.

import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";
import { browserInstallKey, INSTALL_KEY_FILE } from "./install-key.ts";

const here = dirname(fileURLToPath(import.meta.url));

/** Paths inside playwright-core the daemon never loads (host setup scripts, viewers, typings). */
// capybara:allow-module-state read-only constant (build script, never loaded by the kernel)
const VENDOR_SKIP = [/^bin([/\\]|$)/, /^lib[/\\]vite([/\\]|$)/, /^types([/\\]|$)/, /\.d\.ts$/];

export async function buildDaemon(outDir = join(here, "..", "dist", "service")): Promise<void> {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  await build({
    entryPoints: [join(here, "cli.ts")],
    outfile: join(outDir, "daemon.mjs"),
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    legalComments: "inline",
    banner: { js: "// @capybara-hq/plugin-browser daemon (generated by daemon/build.ts)" },
    plugins: [
      {
        name: "vendor-playwright-core",
        setup(b) {
          b.onResolve({ filter: /^playwright-core(\/.*)?$/ }, (args) => {
            const sub = args.path.slice("playwright-core".length);
            const target = sub === "" ? "/index.mjs" : `${sub}.js`;
            return { path: `./vendor/playwright-core${target}`, external: true };
          });
        },
      },
    ],
  });
  const require = createRequire(join(here, "..", "package.json"));
  const pkgDir = dirname(require.resolve("playwright-core/package.json"));
  const version = (
    JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")) as { version: string }
  ).version;
  cpSync(pkgDir, join(outDir, "vendor", "playwright-core"), {
    recursive: true,
    dereference: true,
    filter: (src) => {
      const rel = relative(pkgDir, src);
      if (rel === "") return true;
      if (rel.split(sep).includes("node_modules")) return false;
      return !VENDOR_SKIP.some((re) => re.test(rel));
    },
  });
  const key = browserInstallKey(readFileSync(join(pkgDir, "browsers.json"), "utf8"));
  writeFileSync(join(outDir, INSTALL_KEY_FILE), `${key}\n`);
  process.stderr.write(`daemon built into ${outDir} (playwright-core ${version}, ${key})\n`);
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  await buildDaemon(process.argv[2]);
}
