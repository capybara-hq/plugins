// Regenerates src/operation-agent-source.ts from runtime/capybara-operation.py (the provider
// stages the agent from that TypeScript string: the packed plugin bundles src, not runtime/).
// Run from the repository root: node plugins/sandbox-e2b/scripts/gen-agent-source.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(new URL("../runtime/capybara-operation.py", import.meta.url), "utf8");
const digest = createHash("sha256").update(source).digest("hex");
writeFileSync(
  new URL("../src/operation-agent-source.ts", import.meta.url),
  [
    "// Generated by scripts/gen-agent-source.mjs from runtime/capybara-operation.py; do not edit.",
    "",
    "/** SHA-256 of the agent source below. */",
    `export const OPERATION_AGENT_SHA256 = ${JSON.stringify(digest)};`,
    "",
    "/** The provider's in-VM operation agent (runtime/capybara-operation.py). */",
    `export const OPERATION_AGENT_SOURCE = ${JSON.stringify(source)};`,
    "",
  ].join("\n"),
);
